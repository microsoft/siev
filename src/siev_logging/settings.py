"""
SIEV Logging Configuration - Centralized configuration for logging behavior.

Provides default configurations and environment-based overrides for:
- Log levels and output destinations
- File rotation and retention policies  
- Progress tracking settings
- Performance monitoring options
"""

import os
from typing import Dict, Any


# Default logging configuration
DEFAULT_CONFIG = {
    # Log levels
    "console_level": "PROGRESS",
    "file_level": "INFO", 
    "error_level": "WARNING",
    "debug_enabled": False,
    
    # Output options
    "json_output": False,
    "use_colors": None,  # Auto-detect
    
    # File rotation
    "rotation_size": "10MB",
    "rotation_count": 5,
    "retention_days": 30,
    
    # Progress tracking
    "show_progress_bar": True,
    "show_eta": True,
    "progress_update_interval": 1.0,  # seconds
    
    # Performance monitoring
    "track_api_calls": True,
    "track_operations": True,
    "performance_summary": True
}

# Environment variable mappings
ENV_MAPPINGS = {
    "SIEV_LOG_LEVEL": "console_level",
    "SIEV_FILE_LOG_LEVEL": "file_level", 
    "SIEV_DEBUG": "debug_enabled",
    "SIEV_JSON_LOGS": "json_output",
    "SIEV_NO_COLORS": "use_colors",
    "SIEV_LOG_ROTATION_SIZE": "rotation_size",
    "SIEV_LOG_RETENTION_DAYS": "retention_days"
}


def load_config(config_override: Dict[str, Any] = None) -> Dict[str, Any]:
    """
    Load logging configuration from defaults, environment variables, and overrides.
    
    Args:
        config_override: Dictionary of configuration overrides
        
    Returns:
        Complete configuration dictionary
    """
    
    config = DEFAULT_CONFIG.copy()
    
    # Apply environment variable overrides
    for env_var, config_key in ENV_MAPPINGS.items():
        env_value = os.environ.get(env_var)
        if env_value is not None:
            # Convert string values to appropriate types
            if config_key in ["debug_enabled", "json_output", "show_progress_bar", "show_eta", 
                             "track_api_calls", "track_operations", "performance_summary"]:
                config[config_key] = env_value.lower() in ("true", "1", "yes", "on")
            elif config_key in ["rotation_count", "retention_days"]:
                config[config_key] = int(env_value)
            elif config_key == "progress_update_interval":
                config[config_key] = float(env_value)
            elif config_key == "use_colors" and env_var == "SIEV_NO_COLORS":
                config[config_key] = not (env_value.lower() in ("true", "1", "yes", "on"))
            else:
                config[config_key] = env_value
    
    # Apply explicit overrides
    if config_override:
        config.update(config_override)
    
    return config


def get_log_directory() -> str:
    """Get the log directory from environment or default."""
    return os.environ.get("SIEV_LOG_DIR", "logs")


def setup_experiment_context(experiment_name: str, 
                            model: str, 
                            dataset: str = None,
                            **kwargs) -> Dict[str, Any]:
    """
    Set up logging context for an experiment.
    
    Args:
        experiment_name: Name of the experiment
        model: Model being evaluated
        dataset: Dataset being used
        **kwargs: Additional context fields
        
    Returns:
        Context dictionary for logging
    """
    
    context = {
        "experiment_name": experiment_name,
        "model": model,
        "start_time": None,  # Will be set by logger
        "session_id": None   # Will be generated by logger
    }
    
    if dataset:
        context["dataset"] = dataset
    
    context.update(kwargs)
    return context


