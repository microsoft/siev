def get_experiment_config(config_name: str) -> Dict[str, Any]:
    """Get a pre-defined experiment configuration."""
    if config_name not in EXPERIMENT_CONFIGS:
        raise ValueError(f"Unknown config: {config_name}. Available: {list(EXPERIMENT_CONFIGS.keys())}")
    
    base_config = load_config()
    base_config.update(EXPERIMENT_CONFIGS[config_name])
    return base_config